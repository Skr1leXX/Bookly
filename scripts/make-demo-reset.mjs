// Builds supabase/demo-reset.sql: a pg_cron job that re-runs supabase/seed.sql every night, so a public demo
// returns to its original state by itself. Run after changing seed.sql:  npm run demo:reset-sql
import fs from "node:fs";

const seed = fs.readFileSync(new URL("../supabase/seed.sql", import.meta.url), "utf8");
if (seed.includes("$seed$")) throw new Error("seed.sql must not contain the $seed$ quote tag");

const out = `-- Nightly reset of the DEMO data (generated by scripts/make-demo-reset.mjs from seed.sql; do not edit by hand).
--
-- Use ONLY in a demo project: the job deletes and recreates the demo organizations and the demo users
-- (*@bookly.test, *@borodach.test) every night at 03:00 UTC. Accounts that visitors registered themselves are not touched.
-- Run this file once in the Supabase SQL Editor. To stop the job:  select cron.unschedule('bookly-demo-reset');

create extension if not exists pg_cron with schema pg_catalog;

select cron.schedule('bookly-demo-reset', '0 3 * * *', $seed$
${seed.trim()}
$seed$);
`;
fs.writeFileSync(new URL("../supabase/demo-reset.sql", import.meta.url), out);
console.log(`supabase/demo-reset.sql written (${out.length} bytes)`);
